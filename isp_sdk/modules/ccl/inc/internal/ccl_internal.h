/**
 * @brief bit masks for finished stages of frame processing
 * @details NOTE that empty bit is never set, so bit 0 is always 0. */
typedef enum
{
    CCL_FRAME_STATE_EMPTY,
    CCL_FRAME_STATE_PRE_ISP_PREP,
    CCL_FRAME_STATE_ISP_PROCESSING,
    CCL_FRAME_STATE_ISP_PROCESSED,
    CCL_FRAME_STATE_READY,
    CCL_FRAME_STATE_CCA_PROCESSING,
    CCL_FRAME_STATE_CCA_PROCESSED,
    CCL_FRAME_STATE_APP_PROCESSING,
    CCL_FRAME_STATE_APP_PROCESSED,
    CCL_FRAME_STATE_COUNT
}ccl_FrameState_t;

typedef struct
{
#if CCL_FEATURE_CONTEXT_MATCH
    /** @brief all data associated with ISP processing*/
    isp_HDR_MERGE_t mHdrCfg;
#endif
    /** @brief Camera sensor configuration
     * @details This can be values obtained from CCA (such ccl_HwCfgs_t are used in stream's cfg history)
     *  or parsed from embedded data */
    cca_SensPrm_t mSensCfg;
    /** @brief Id of frame this cfg is based on */
    uint32_t mBasedOnId;
}ccl_HwCfg_t;

typedef struct
{
    /** @brief Input planes (image data) */
    cca_ImgBuf_t mImg[CCL_INBUF_PLANE_CNT];

    /** @brief Embedded data (pointing to first plane's embedded region) */
    cca_EmbdData_t mEmbed;

    /** @brief Applied lens position when captured */
    int32_t mLensPosition;

    /** @brief Frame Id as set by capture API (do not confuse with isp_Task_t's meta info mFrameIdx)*/
    uint64_t mFrameNo;

    /** @brief Buffer ID as set internally by capture system */
    uint64_t mBufId;

    /** @brief Capture timestamp in nanoseconds */
    uint64_t mCaptureTimeNs;
}ccl_CapBuf_t;

typedef struct
{
    /** @brief Frame data (both image and meta)*/
    ccl_Frame_t FrameData;
    /** @brief Input data as generated by capture system */
    ccl_CapBuf_t *mInBuf;

    /** @brief ISP configuration
     * @details This is the setting that the frame was/is-going-to be processed with on ISP.
     * The config is partially created during stream open (buf pointers) and partially after
     * frame was associated with one of the generated cfg in cfg history (updated immediately
     * after frame capture */
    isp_Task_t *mIspCfg;

    /** @brief Any error that might have occurred after ISP processing.
     * @details Note that this field is only valid after FRAME_DONE event. */
    uint32_t mIspError;

    /** @brief Task's physical location in RAM
     * @details Do not mistake with img buf PHY locations, those are part of frame data */
    uint64_t mIspPhy;

    /** @brief Work pointers for image buffers, used only for alloc() and free()
     * @details This is needed only due to streaming mode, where we process embedded data in ISP.
     * As we do not want to report emb region in output image (but need the space in output buffer), we move
     * IO buf's mpData (work pointer) after the embedded data, thus loosing original pointer for free().
     * Therefore we store the original pointer here. */
    void *mpAllocImgBufs[CCA_IOBUFT_CNT];

    /** @brief Phy addresses for image buffers
     * @details This is needed only due to streaming mode, where we process embedded data in ISP.
     * As we do not want to report emb region in output image (but need the space in output buffer), we move
     * IO buf's mHwAddr (phy address) after the embedded data, thus loosing original address for ISP task.
     * Therefore we store the original pointer here. */
    uint64_t mImgBufsBasePhy[CCA_IOBUFT_CNT];

    /** @brief Actual sensor configuration as reconstructed from embedded data */
    cca_SensPrm_t mActSensCfg;

#if CCL_FEATURE_CONTEXT_MATCH
    /** @brief Expected sensor configuration as stored in cfg history */
    cca_SensPrm_t mExpSensCfg;
#endif

    /** @brief  Flags of finished processing stages */
    uint32_t mStateFlags;
#if CCL_FEATURE_LOG_FRAME_TIMES
    /** @brief Timestamp for each state entry in usec UNIX time */
    uint64_t mTimeStamps[CCL_FRAME_STATE_COUNT];
#endif

}ccl_FrameTask_t;

typedef struct
{
    /**
     * @brief Initializes capture method and attached sensor for given stream
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     * @param apCfg - params specific for given capture method, supplied during ccl_Open()
     * @param apCamInitParams - params specific for sensor attached to this stream, supplied during ccl_Open()
     * @return 0 on success or negative error otherwise.
     *
     * @details The method should do full power-up sequence including:
     * - Initialization of capture API
     * - allocation of required resources, driver connections
     * - read of params from the sensor
     * It should not give command to capture frames yes.
     */
    int32_t (*mpCapOpen)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId, ccl_CapParams_t *apCfg, cca_CamInit_t *apCamInitParams);
    /**
     * @brief Complete power-down and reals of resources for capture method and given sensor
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     */
    void (*mpCapClose)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId);

    /**
     * @brief Signal to capture method to start sending captured frames on given stream
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     * @return 0 on success or negative error otherwise.
     */
    int32_t (*mpCapStart)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId);
    /**
     * @brief Signal to capture method to stop sending captured frames on given stream (but remain prepared - "pause")
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     * @return 0 on success or negative error otherwise.
     *
     * @details Please note that this also implies that all capture buffers are now returned to capture system.
     */
    int32_t (*mpCapStop)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId);

    /**
     * @brief Request for sensor reconfiguration
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     * @param AsyncOk - Indication if a call can return before new configuration was enforced on sensor (if false, call must return only after sensor runs on new cfg)
     * @param apSensCfg - New configuration for the sensor
     * @return 0 on success or negative error otherwise.
     */
    int32_t (*mpCapSensorUpdate)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId, bool AsyncOk, cca_SensPrm_t *apSensCfg, cca_CamInit_t *apCamInitParams, uint32_t aBasedOnId);

    /**
     * @brief Information for capture subsytem that previously given buffer (via ccl_NewInImg()) is no longer in use
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     *
     * @details Note that this event can be generated also after mpCapStop() was called.
     * At present is this event generated every time capture buffer is freed with single exception ->
     * -> a call to ccl_DropReady() will not generate this call.
     */
    void (*mpCapBufReturn)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId, ccl_CapBuf_t *apBuf);

    /**
     * @brief Returns full height of picture as it comes into ISP (only called in streaming mode)
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     */
    uint32_t (*mpGetFullHeight)(ccl_CapCfg_t *apCfg, uint32_t *apEmbSizeBefore, uint32_t *apEmbSizeAfter);

    /**
     * @brief Notification that ISP just processed a frame (Frame_done event)
     *
     * @param aHwId - ISP block the stream is running on
     * @param aCamId - ISP pipe in the block stream is running on
     */
    void (*mpFrameDoneEvt)(ispdrv_HwId_t aHwId, ispdrv_CamPipeId_t aCamId);

    /** @brief Indicates if this capture subsystem supports Streaming mode (M2M mode is mandatory) */
    bool StreamingModeSupported;
}ccl_CapOps_t;

